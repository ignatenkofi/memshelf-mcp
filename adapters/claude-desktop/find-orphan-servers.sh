#!/usr/bin/env bash
# Найти инстансы сервера, оставшиеся без клиента (#115).
#
# ЗАЧЕМ. 21.08 Claude Desktop поднял ДВА дерева процессов сервера за один
# запуск приложения. Один обслуживал сессию, второй прожил не меньше
# 25 минут, ничего не делая и не имея возможности хоть что-то сказать:
# stdout и stderr у него в `/dev/null`. Разбор нашёл его вручную — и
# детектор остался жить в тексте issue. Следующий разбор писал бы его
# заново, поэтому он здесь файлом. Это ровно та половина #115, которая не
# требует решений: три вопроса дизайна (кто сообщает, где лежит advisory,
# область применимости) остаются за владельцем и здесь не трогаются.
#
# ЧЕМ РАЗЛИЧАЮТСЯ ИНСТАНСЫ. Не временем старта и не порядком в `ps`, а
# дескриптором 1: у живого он ведёт в лог хоста, у осиротевшего — в
# `/dev/null`. Признак взят из замера в issue, а не придуман:
#
#   1312  1w REG  ~/Library/Logs/Claude/mcp-server-memshelf.log   ← живой
#   1323  1u CHR  /dev/null                                       ← осиротевший
#
# КОДЫ ВОЗВРАТА (конвенция портфеля):
#   0 — осиротевших нет (живые могут быть, а могут и не быть);
#   1 — НАЙДЕНЫ осиротевшие, перечислены с pgid;
#   2 — ПРОВЕРИТЬ НЕЧЕМ: нет lsof, или ни одного процесса по шаблону.
#       Отдельный код, а не «чисто»: «серверов не запущено» и «серверов
#       без клиента нет» — разные ответы, и путать их значит повторять
#       ровно ту болезнь, ради которой issue заведён.
#
#   adapters/claude-desktop/find-orphan-servers.sh
#
# Переменные (для фикстур и для нестандартных установок):
#   ORPHAN_PATTERN  шаблон pgrep -f   (по умолчанию memshelf-сервер)
#   ORPHAN_LOG_HINT подстрока пути лога хоста в выводе lsof
#
# Убивать найденное скрипт не умеет намеренно: `kill -TERM -<pgid>` в
# автоматическом режиме — это способ однажды прибить живой инстанс из-за
# промаха шаблона. Команда печатается, нажимает человек.
set -uo pipefail

PATTERN="${ORPHAN_PATTERN:-.venv/bin/python3.*memshelf}"
LOG_HINT="${ORPHAN_LOG_HINT:-mcp-server-memshelf.log}"

command -v lsof >/dev/null 2>&1 || {
    echo "find-orphan-servers: нет lsof — проверить нечем" >&2
    exit 2
}

# `pgrep -f` матчит ПОЛНУЮ командную строку, поэтому в улов попадает и сам
# разбор: шелл, в котором набран однострочник с шаблоном, содержит шаблон в
# своём `args`. Проверено на первом же прогоне этого файла — в контейнере
# без единого сервера детектор нашёл «двух осиротевших», и обоими оказались
# bash-обёртки вызова. Версия из тела issue этого фильтра не имеет.
#
# Отсев двойной: собственное дерево по pid и родителю плюс требование,
# чтобы ИМЯ исполняемого файла (`comm`, не `args`) было интерпретатором.
# Одного отсева себя мало: соседний шелл с тем же текстом в строке под него
# не подпадает.
self_pids=" $$ $PPID "
pids=""
for p in $(pgrep -f "$PATTERN" 2>/dev/null || true); do
    case "$self_pids" in *" $p "*) continue ;; esac
    comm="$(ps -o comm= -p "$p" 2>/dev/null | tr -d ' ')"
    case "$comm" in *python*|*uv*) pids="${pids}${pids:+ }$p" ;; esac
done
if [ -z "$pids" ]; then
    echo "find-orphan-servers: по шаблону '$PATTERN' не найдено ни одного процесса — проверять нечем" >&2
    exit 2
fi

live=0
orphans=""
for p in $pids; do
    # Дескриптор 1 конкретного процесса; отсутствие вывода — тоже ответ
    # (процесс исчез между pgrep и lsof), и он читается как осиротевший
    # не должен: такой pid просто пропускается.
    fd1="$(lsof -a -d 1 -p "$p" 2>/dev/null || true)"
    [ -n "$fd1" ] || continue
    if printf '%s' "$fd1" | grep -q "$LOG_HINT"; then
        live=$((live + 1))
        echo "live:   $p"
    else
        pgid="$(ps -o pgid= -p "$p" 2>/dev/null | tr -d ' ')"
        orphans="${orphans}${orphans:+ }${p}"
        echo "orphan: $p (pgid ${pgid:-?}) — stdout не ведёт в лог хоста"
    fi
done

echo
if [ -z "$orphans" ]; then
    echo "find-orphan-servers: живых $live, осиротевших нет"
    exit 0
fi

echo "find-orphan-servers: живых $live, ОСИРОТЕВШИХ $(printf '%s' "$orphans" | wc -w | tr -d ' ')"
echo "Снять (по одному, глазами сверив pgid — автоматически скрипт этого не делает):"
for p in $orphans; do
    pgid="$(ps -o pgid= -p "$p" 2>/dev/null | tr -d ' ')"
    [ -n "$pgid" ] && echo "  kill -TERM -$pgid"
done
exit 1
